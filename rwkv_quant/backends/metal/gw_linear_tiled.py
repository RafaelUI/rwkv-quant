"""Заглушка ПРИОРИТЕТА 1 -- тайловый GEMM с декодом в threadgroup-памяти.

Ядра ЕЩЁ НЕТ. Функция ниже -- псевдоним эталона (закон 30, приём как в
fused_prewkv.py 11.09): она форсирует ПЛОТНЫЙ путь GwQuantLinear
(_dequant_w + matmul) на ЛЮБОМ N, временно подняв GEMM_MIN_BATCH_NB так,
чтобы обойти чанки по NB_CHUNK=4. Плотный путь уже бит-в-бит с writer
(iначе весь проект был бы сломан), поэтому для N < 128 он играет роль
эталона: НАСТОЯЩИЙ тайловый кернель обязан совпасть с ним, а не с
chunked nb-путём, который сам под вопросом на границах чанка.

Пока эта функция -- лишь форсированный плотный путь, гейт ниже обязан
идти ТРИВИАЛЬНО ЗЕЛЁНЫМ (оба плеча буквально один и тот же плотный
путь). Когда появится настоящий tiled-кернель, gw_linear_tiled
заменяется на вызов кернеля, и гейт становится содержательным без
переписывания самого гейта.
"""
from . import quant_linear_gw as gw


def gw_linear_tiled(qlin: "gw.GwQuantLinear", x):
    """Форсирует плотный (dense-dequant) путь GwQuantLinear на любом N.
    ВРЕМЕННО поднимает модульный порог, вызывает __call__, откатывает."""
    old = gw.GEMM_MIN_BATCH_NB
    gw.GEMM_MIN_BATCH_NB = 1
    try:
        return qlin(x)
    finally:
        gw.GEMM_MIN_BATCH_NB = old
