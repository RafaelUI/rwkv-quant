"""
Готовые пресеты quick-start API. Калиброваны эмпирически на rwkv7-g1h-1.5b
(см. examples/ и историю ablation в calibration/). Битность/outlier_frac —
отправная точка, не гарантия для другого масштаба модели: на RWKV-7
чувствительность к квантованию НЕ переносится линейно между размерами
(например, group 'small' безобидна на 61M, но катастрофична на 1.5B без
outlier-обработки) -- см. README. Для продакшена -- rwkv_quant.calibrate() на целевом
чекпоинте перед выбором пресета (scripts/ -- заглушки).

Оба пресета ниже зафиксированы по итогам сессий 19.07-5/6/7 (см.
NEXT_SESSION.md) -- это не первая калибровка "на глаз", а Парето-точки,
подтверждённые прямым замером ppl на eval_corpus_world.pt[:8], одна и та
же схема квантования (asym_sb6[_aw], блок 32/суперблок 8), REDUCTION --
буквально "COMPRESSION с большей битностью кода" (аналогия MXFP4/MXFP8:
один и тот же блочный scale-механизм, разная точность мантиссы), а не
другая техника ради лучшего числа.

ОБЕ схемы требуют activation-статистику (act_stats_path) для AW-критерия
поиска -- см. tests/collect_act_stats.py (~28с сборки, /tmp/act_stats_1p5b.pt
не переживает перезагрузку -- пересобрать перед использованием, если файла
нет). ПРИ ОТСУТСТВИИ ФАЙЛА AW-режимы молча вырождаются в свои
_search-варианты: артефакт остаётся корректным, но ОТЛИЧАЕТСЯ от того, что
получится при наличии статистики. То есть один и тот же вызов даёт разный
файл в зависимости от содержимого /tmp. Для воспроизводимости задавать путь
явно либо ставить act_stats_path=None.

small=16 (04.08, было 8). Группа small -- это k_k / k_a / r_k, 147K
параметров на 1.5B, 0.01% модели. Leave-one-out по группам
(tests/ablate_group_contrib.py) показал, что она уносит 1.59 из 2.36 п.п.
деградации REDUCTION -- ДВЕ ТРЕТИ, тогда как proj+cmix+emb_head вместе
дают 0.69. Причина в том, что k_k/k_a/r_k -- поканальные модуляторы ВНУТРИ
рекуррентности (нормировка ключа, темп in-context обучения,
receptance-бонус): их ошибка не портит одно предсказание, а искажает
обновление состояния и копится по длине последовательности. Отсюда же
рост деградации с контекстом (+1.52% на 128 токенах против +2.57% на 512,
tests/eval_corpora_compare.py).

Не квантовать их стоит +0.14 МБ, то есть 0.011% файла. Замерено на обоих
масштабах (tests/confirm_small_fix.py, tests/eval_2p9b_one.py),
мультиязычный корпус, 512 токенов:
  1.5B REDUCTION   2.36% -> 0.77%   (сербский 5.52% -> 1.00%)
  1.5B COMPRESSION 5.41% -> 3.63%
  2.9B REDUCTION   1.52% -> 1.37%
  2.9B COMPRESSION 4.38% -> 4.24%
Прежнее значение 8 подбиралось на eval_corpus_world[:8] -- срезе из 1016
предсказаний короткого английского, который занижает деградацию вшестеро
(см. закон 9 в NEXT_SESSION.md).
"""
from .calibration.group_config import QuantConfig

# REDUCTION v2: цель -- деградация около нуля (для QAT/QLoRA-базы, где
# training чувствителен даже к небольшим потерям -- см. сессию 19.07-5).
# proj=6 БЕЗ AW (asym_sb6 plain): на 6 битах AW-взвешивание для proj
# ПЕРЕВОРАЧИВАЕТ знак выигрыша (сессия 19.07-5, изоляция по стадиям
# конвейера) -- контринтуитивно, но подтверждено замером, не теорией.
# emb_head=6 И cmix=6 -- С AW (там оно по-прежнему помогает на этой
# битности), proj=6 -- БЕЗ AW (asym_sb6).
# ЧИСЛА (мультиязычный корпус, 19456 предсказаний, реальный путь
# real_gw=True): 1.5B +0.77% при 1255.4 МБ, 2.9B +1.37% при 2420.9 МБ.
# Прежний докстринг обещал +0.12% -- это была цифра с англоязычного
# среза на 1016 предсказаний, который занижает деградацию вшестеро
# (закон 9 в NEXT_SESSION.md).
# int6 полностью деплоится: writer пакует 2-ю битплоскость qh2,
# кернель (quant_linear_gw.py, кернель-3) декодит int4/5/6 бит-в-бит
# с writer'ом; decode ~17.7 мс/ток на M4 base (A/B 19.07).
# ПЕРЕСОБРАН 16.08. Всё измерено на ОБОИХ чекпоинтах реальным путём
# (`real_gw=True`), композитом на полном мультиязычном корпусе:
#
#   1.5B: 1255.4 МБ +0.772%  ->  1434.7 МБ (2.13x от bf16) +0.108%
#   2.9B: 2420.9 МБ +1.370%  ->  2736.8 МБ (2.15x от bf16) +0.157%
#
# то есть деградация в 7.1 и 8.7 раза меньше за +14% и +13% файла. Ни
# одного размена по языкам: на 2.9B сербский идёт +1.156% -> +0.013%
# (fake-путь), на 1.5B все три улучшаются на каждом шаге.
#
# Три правки, каждая измерена отдельно и на обоих масштабах:
#
#   cmix/proj/head/emb -> Q6_K-раскладка (`sym_aw`, блок 16). Блок вдвое
#     уже при 8-битном масштабе блока -- на шести битах отдельный min не
#     окупается, мы платили за него дважды. Вклад cmix падает в 75 раз.
#   proj 6 -> 8 бит. Крупнейшая правка из оставшихся: +0.111% -> +0.035%
#     на 1.5B и +0.275% -> +0.099% на 2.9B (fake), цена +100.6 и +209.7 МБ.
#   head и emb 6 -> 8 бит. Для head рычаг именно битность, а не раскладка
#     (раскладка сама по себе на нём из шума не выходит). Для emb решение
#     принято по KL: он снимает 9% композитного KL на 1.5B и 13.4% на
#     2.9B там, где ppl на 1.5B не видит ничего.
#
# ПОЧЕМУ РАЗМЕР ВЫРОС И ПОЧЕМУ ЭТО ВЕРНО. Функция полезности REDUCTION --
# QLoRA и векторные модели: «в 2-2.5 раза меньше bf16 при сопоставимом
# качестве», борьбы за мегабайт там нет. Прежний пресет сидел на 2.43x,
# то есть у верхнего края коридора, и оставлял качество недобранным.
# Для COMPRESSION из этого не следует НИЧЕГО -- там функция полезности
# другая, и пресет не тронут.
#
# `emb_head` разделён на `emb` и `head`: битность у них теперь одна, но
# раскладка и роль разные, и `calibrate()` подбирает их порознь.
REDUCTION = QuantConfig(
    proj=8, cmix=6, emb=8, head=8,
    w_lora=6, a_lora=6, v_lora=6, g_lora=8, small=16,
    outlier_fracs={},
    group_scale={"proj": 16, "cmix": 16, "emb": 16, "head": 16,
                 "w_lora": 64, "a_lora": 64, "v_lora": 64},
    group_scale_mode={"proj": "sym_aw", "cmix": "sym_aw",
                      "emb": "sym_aw", "head": "sym_aw"},
    act_stats_path="/tmp/act_stats_1p5b.pt",
)

# COMPRESSION: "чемпион" из сессий 17.07-18.07. ЧИСЛА (мультиязычный
# корпус): 1.5B +3.63% при 970.2 МБ, 2.9B +4.24% при 1854.7 МБ.
# Прежний докстринг обещал +2.4% -- см. замечание про корпус у REDUCTION.
# group-wise asym_sb6_aw
# (блок 32, суперблок 8, 6-бит qs/qm scale/min, AW-взвешенный поиск) --
# ПОЛНОСТЬЮ деплоится (bits 4/5, реальный кернель есть, real_gw=True
# работает, backends/metal/quant_linear_gw.py). Заменяет старый
# per-row+SpQR COMPRESSION (ppl 18.15/+59%, ~1181MB) -- при похожем
# размере вдвое меньшая деградация за счёт groupwise-квантования вместо
# per-row (см. README/NEXT_SESSION: "ГРАНУЛЯРНОСТЬ ВАЖНЕЕ БИТНОСТИ").
# Проверено сессией 19.07-7: дальнейшее ужатие (напр. до 4x от bf16)
# НЕДОСТИЖИМО в текущем нибл-формате даже ценой ухода за 5% ppl --
# cmix (47% размера) уже на полу int4 (INT3 в нибл-контейнере не
# экономит байт). Эта точка близка к границе Парето-фронта формата, не
# под-оптимизирована -- дальше только принципиально новая упаковка
# (суб-ниббл/sparsity), не тюнинг битности.
COMPRESSION = QuantConfig(
    proj=5, cmix=4, emb_head=5,
    w_lora=6, a_lora=6, v_lora=6, g_lora=8, small=16,
    outlier_fracs={},
    group_scale={"proj": 32, "cmix": 32, "emb_head": 32,
                 "w_lora": 64, "a_lora": 64, "v_lora": 64},
    group_scale_mode={"proj": "asym_sb6_aw", "cmix": "asym_sb6_aw",
                      "emb_head": "asym_sb6_aw"},
    act_stats_path="/tmp/act_stats_1p5b.pt",
)

PRESETS = {"reduction": REDUCTION, "compression": COMPRESSION}
